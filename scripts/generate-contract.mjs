import fs from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import SwaggerParser from "@apidevtools/swagger-parser";
import { fileURLToPath } from "node:url";
const path = new URL("../docs/api_contract.yaml", import.meta.url);
await SwaggerParser.validate(fileURLToPath(path));
const contract = JSON.parse(await fs.readFile(path, "utf8"));
await fs.writeFile(
  new URL("../packages/web_api/src/schema.ts", import.meta.url),
  astToString(await openapiTS(contract)),
);
// Deliberately small DTO generator for this contract's named object schemas.
// Unsupported schema constructs fail instead of silently generating incorrect types.
function dartType(s) {
  if (s.$ref) return s.$ref.split("/").pop() + "Dto";
  if (s.type === "string") return "String";
  if (s.type === "integer") return "int";
  if (s.type === "number") return "double";
  if (s.type === "boolean") return "bool";
  if (s.type === "array") return `List<${dartType(s.items)}>`;
  if (s.type === "object") return "Map<String, dynamic>";
  throw new Error("Unsupported schema " + JSON.stringify(s));
}
function decode(s, key) {
  const access = `json['${key}']`;
  if (s.type === "number") return `(${access} as num).toDouble()`;
  if (s.$ref)
    return `${dartType(s)}.fromJson(Map<String, dynamic>.from(${access} as Map))`;
  if (s.type === "array") {
    if (!s.items.$ref && s.items.type !== "object") {
      throw new Error(
        "This DTO generator only supports arrays of object schemas",
      );
    }
    return `(${access} as List).map((value) => ${s.items.$ref ? dartType(s.items) + ".fromJson(Map<String, dynamic>.from(value as Map))" : "Map<String, dynamic>.from(value as Map)"}).toList()`;
  }
  return `${access} as ${dartType(s)}`;
}
let dart = "// Generated by scripts/generate-contract.mjs. Do not edit.\n";
for (const [name, schema] of Object.entries(contract.components.schemas)) {
  dart += `\nclass ${name}Dto {\n`;
  for (const [field, s] of Object.entries(schema.properties))
    dart += `  final ${dartType(s)}${schema.required.includes(field) ? "" : "?"} ${field};\n`;
  dart +=
    `  ${name}Dto.fromJson(Map<String, dynamic> json)\n    : ` +
    Object.entries(schema.properties)
      .map(
        ([field, s]) =>
          `${field} = ${schema.required.includes(field) ? decode(s, field) : `json['${field}'] == null ? null : ${decode(s, field)}`}`,
      )
      .join(",\n      ") +
    ";\n}\n";
}
await fs.writeFile(
  new URL("../packages/mobile_api/lib/contract.g.dart", import.meta.url),
  dart,
);
console.log(
  "OpenAPI validated; TypeScript definitions and Dart DTOs generated.",
);
